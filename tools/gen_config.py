def kcfg_default(typ, default):
    if typ == "Bool":
        return "true" if default else "false"
    return str(default)


def write_schema():
    entries = []
    for _, groups in OPTIONS:
        for g in groups:
            if "toggle" in g:
                key, default = g["toggle"]
                entries.append((key, "Bool", default))
            for key, typ, default, _, _ in g["options"]:
                entries.append((key, typ, default))
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by tools/gen_config.py. Do not edit by hand. -->',
        '<kcfg xmlns="http://www.kde.org/standards/kcfg/1.0"',
        '      xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
        '      xsi:schemaLocation="http://www.kde.org/standards/kcfg/1.0',
        '      http://www.kde.org/standards/kcfg/1.0/kcfg.xsd">',
        '  <kcfgfile name=""/>',
        '  <group name="">',
    ]
    for key, typ, default in entries:
        lines.append(f'    <entry name="{key}" type="{typ}">')
        lines.append(f'      <default>{kcfg_default(typ, default)}</default>')
        lines.append('    </entry>')
    lines += ['  </group>', '</kcfg>', '']
    out = ROOT / "config" / "main.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    return out


class Ui:
    def __init__(self):
        self.lines = []
        self.n = 0

    def name(self, prefix):
        self.n += 1
        return f"{prefix}_{self.n}"

    def add(self, depth, text):
        self.lines.append("  " * depth + text)

    def prop(self, d, name, kind, value):
        self.add(d, f'<property name="{name}"><{kind}>{value}</{kind}></property>')

    def option_rows(self, d, options):
        """A form layout: checkboxes span both columns, others get a label."""
        self.add(d, f'<layout class="QFormLayout" name="{self.name("form")}">')
        for row, (key, typ, default, label, extra) in enumerate(options):
            if typ == "Bool":
                self.add(d + 1, f'<item row="{row}" column="0" colspan="2">')
                self.add(d + 2, f'<widget class="QCheckBox" name="kcfg_{key}">')
                self.prop(d + 3, "text", "string", escape(label))
                self.add(d + 2, '</widget>')
                self.add(d + 1, '</item>')
                continue
            self.add(d + 1, f'<item row="{row}" column="0">')
            self.add(d + 2, f'<widget class="QLabel" name="{self.name("label")}">')
            self.prop(d + 3, "text", "string", escape(label))
            self.add(d + 2, '</widget>')
            self.add(d + 1, '</item>')
            self.add(d + 1, f'<item row="{row}" column="1">')
            if typ == "Int":
                lo, hi, suffix = extra
                self.add(d + 2, f'<widget class="QSpinBox" name="kcfg_{key}">')
                self.prop(d + 3, "minimum", "number", lo)
                self.prop(d + 3, "maximum", "number", hi)
                self.prop(d + 3, "suffix", "string", escape(suffix))
            else:
                self.add(d + 2, f'<widget class="KColorButton" name="kcfg_{key}">')
            self.add(d + 2, '</widget>')
            self.add(d + 1, '</item>')
        self.add(d, '</layout>')

    def group(self, d, g):
        if "toggle" in g:
            key, _ = g["toggle"]
            self.add(d, f'<widget class="QGroupBox" name="kcfg_{key}">')
            self.prop(d + 1, "checkable", "bool", "true")
        else:
            self.add(d, f'<widget class="QGroupBox" name="{self.name("group")}">')
        self.prop(d + 1, "title", "string", escape(g["title"]))
        self.add(d + 1, f'<layout class="QVBoxLayout" name="{self.name("vbox")}">')
        if g.get("text"):
            self.add(d + 2, '<item>')
            self.add(d + 3, f'<widget class="QLabel" name="{self.name("label")}">')
            self.prop(d + 4, "text", "string", escape(g["text"]))
            self.prop(d + 4, "wordWrap", "bool", "true")
            self.add(d + 3, '</widget>')
            self.add(d + 2, '</item>')
        if g["options"]:
            self.add(d + 2, '<item>')
            self.option_rows(d + 3, g["options"])
            self.add(d + 2, '</item>')
        self.add(d + 1, '</layout>')
        self.add(d, '</widget>')


def write_form():
    ui = Ui()
    ui.add(0, '<?xml version="1.0" encoding="UTF-8"?>')
    ui.add(0, '<!-- Generated by tools/gen_config.py. Do not edit by hand. -->')
    ui.add(0, '<ui version="4.0">')
    ui.add(1, '<class>Snap11ConfigForm</class>')
    ui.add(1, '<widget class="QWidget" name="Snap11ConfigForm">')
    ui.add(2, '<layout class="QVBoxLayout" name="mainLayout">')
    ui.add(3, '<item>')
    ui.add(4, '<widget class="QTabWidget" name="tabs">')
    for title, groups in OPTIONS:
        ui.add(5, f'<widget class="QWidget" name="{ui.name("tab")}">')
        ui.add(6, f'<attribute name="title"><string>{escape(title)}</string></attribute>')
        ui.add(6, f'<layout class="QVBoxLayout" name="{ui.name("vbox")}">')
        for g in groups:
            ui.add(7, '<item>')
            ui.group(8, g)
            ui.add(7, '</item>')
        ui.add(7, '<item>')
        ui.add(8, f'<spacer name="{ui.name("spacer")}">')
        ui.add(9, '<property name="orientation"><enum>Qt::Vertical</enum></property>')
        ui.add(8, '</spacer>')
        ui.add(7, '</item>')
        ui.add(6, '</layout>')
        ui.add(5, '</widget>')
    ui.add(4, '</widget>')
    ui.add(3, '</item>')
    ui.add(2, '</layout>')
    ui.add(1, '</widget>')
    ui.add(1, '<customwidgets>')
    ui.add(2, '<customwidget>')
    ui.add(3, '<class>KColorButton</class>')
    ui.add(3, '<extends>QPushButton</extends>')
    ui.add(3, '<header>kcolorbutton.h</header>')
    ui.add(2, '</customwidget>')
    ui.add(1, '</customwidgets>')
    ui.add(1, '<resources/>')
    ui.add(1, '<connections/>')
    ui.add(0, '</ui>')
    out = ROOT / "ui" / "config.ui"
    out.write_text("\n".join(ui.lines) + "\n")
    return out


if __name__ == "__main__":
    print(write_schema())
    print(write_form())
